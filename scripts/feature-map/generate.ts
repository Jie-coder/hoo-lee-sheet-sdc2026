// Feature-map generator.
//
// What it does, in plain words:
//   1. Finds every page in src/app (each page.tsx file is one route).
//   2. Finds every data-testid="..." in src (the stable "buttons" an agent clicks).
//   3. Finds navigation links (router.push("/x") and href="/x") to draw arrows
//      between pages.
//   4. Writes two files next to the hand-written map:
//        routes.generated.json  (machine-readable list of routes, test ids, edges)
//        feature-map.mmd        (Mermaid diagram of the same edges)
//      and renders feature-map.png from the .mmd with mermaid-cli.
//
// Usage:
//   npx tsx scripts/feature-map/generate.ts            # regenerate + render PNG
//   npx tsx scripts/feature-map/generate.ts --no-render  # regenerate only
//   npx tsx scripts/feature-map/generate.ts --check    # fail if anything is stale
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";

const ROOT = path.resolve(import.meta.dirname, "../..");
const APP_DIR = path.join(ROOT, "src/app");
const SRC_DIR = path.join(ROOT, "src");
export const MAP_DIR = path.join(ROOT, ".claude/skills/laluan-feature-map");
const JSON_FILE = path.join(MAP_DIR, "routes.generated.json");
const MMD_FILE = path.join(MAP_DIR, "feature-map.mmd");
const PNG_FILE = path.join(MAP_DIR, "feature-map.png");
const HAND_MAP = path.join(MAP_DIR, "feature-map.md");

// Small helper: list every file under a folder (recursively).
function walk(dir: string): string[] {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const full = path.join(dir, entry.name);
    return entry.isDirectory() ? walk(full) : [full];
  });
}

// Path relative to the repo, always with "/" so output is the same on Windows.
const rel = (file: string) => path.relative(ROOT, file).split(path.sep).join("/");

// "src/app/profile/page.tsx" -> "/profile"; "src/app/page.tsx" -> "/".
// Route groups like "(marketing)" do not appear in the URL, so we drop them.
export function fileToRoute(file: string): string {
  const parts = path.relative(APP_DIR, path.dirname(file)).split(path.sep).filter(Boolean);
  const visible = parts.filter((p) => !(p.startsWith("(") && p.endsWith(")")));
  return "/" + visible.join("/");
}

// Follow "@/components/..." imports from one file (and their imports),
// so a page's arrows include links inside the components it renders.
function componentFiles(file: string, seen = new Set<string>()): string[] {
  if (seen.has(file)) return [];
  seen.add(file);
  const text = fs.readFileSync(file, "utf8");
  for (const match of text.matchAll(/from "@\/components\/([\w\-/]+)"/g)) {
    const base = path.join(SRC_DIR, "components", match[1]);
    const found = [".tsx", ".ts"].map((ext) => base + ext).find((f) => fs.existsSync(f));
    if (found) componentFiles(found, seen);
  }
  return [...seen];
}

// Every internal link target in a file: router.push("/x"), href="/x", push(`/x?...`).
function linkTargets(text: string): string[] {
  const targets = new Set<string>();
  const patterns = [/router\.push\(\s*["`](\/[^"`?$]*)/g, /href=["{]?`?["']?(\/[^"'`?}\s]*)/g];
  for (const pattern of patterns) {
    for (const match of text.matchAll(pattern)) targets.add(match[1] || "/");
  }
  return [...targets];
}

// Every data-testid in a file. Template ids like `persona-card-${id}` are kept
// with "${...}" replaced by "*" so the reader knows it is a family of ids.
function testIds(text: string): string[] {
  const ids = new Set<string>();
  for (const match of text.matchAll(/data-testid=(?:"([^"]+)"|\{`([^`]+)`\})/g)) {
    ids.add((match[1] ?? match[2]).replace(/\$\{[^}]+\}/g, "*"));
  }
  return [...ids].sort();
}

export type GeneratedMap = {
  note: string;
  routes: { route: string; file: string; testIds: string[]; linksTo: string[] }[];
  global: { file: string; testIds: string[]; linksTo: string[] };
};

// Build the whole generated map in memory (no files written here).
export function buildMap(): GeneratedMap {
  const pages = walk(APP_DIR).filter((f) => path.basename(f) === "page.tsx").sort();
  const routes = pages
    .map((page) => {
      const files = componentFiles(page);
      const text = files.map((f) => fs.readFileSync(f, "utf8")).join("\n");
      const route = fileToRoute(page);
      return {
        route,
        file: rel(page),
        testIds: testIds(text),
        linksTo: linkTargets(text).filter((t) => t !== route).sort(),
      };
    })
    .sort((a, b) => a.route.localeCompare(b.route));

  // The layout (site header) is on every page, so it is listed once as "global".
  const layout = path.join(APP_DIR, "layout.tsx");
  const layoutText = componentFiles(layout).map((f) => fs.readFileSync(f, "utf8")).join("\n");
  return {
    note: "GENERATED by scripts/feature-map/generate.ts. Do not edit by hand; run npm run feature-map:render.",
    routes,
    global: { file: rel(layout), testIds: testIds(layoutText), linksTo: linkTargets(layoutText).sort() },
  };
}

// Turn the map into a Mermaid flowchart: one box per page, one arrow per link.
export function toMermaid(map: GeneratedMap): string {
  const id = (route: string) => (route === "/" ? "home" : route.slice(1).replace(/\W/g, "_"));
  const lines = ["%% GENERATED by scripts/feature-map/generate.ts. Do not edit by hand.", "flowchart LR"];
  lines.push('  header(["Site header (every page)"])');
  for (const r of map.routes) lines.push(`  ${id(r.route)}["${r.route}"]`);
  for (const t of map.global.linksTo) lines.push(`  header -.-> ${id(t)}`);
  for (const r of map.routes) for (const t of r.linksTo) lines.push(`  ${id(r.route)} --> ${id(t)}`);
  return lines.join("\n") + "\n";
}

// Problems that make --check fail. Empty list = everything is up to date.
export function findProblems(map: GeneratedMap): string[] {
  const problems: string[] = [];
  const json = JSON.stringify(map, null, 2) + "\n";
  const read = (f: string) => (fs.existsSync(f) ? fs.readFileSync(f, "utf8") : "");
  if (read(JSON_FILE) !== json) problems.push(`${rel(JSON_FILE)} is stale`);
  if (read(MMD_FILE) !== toMermaid(map)) problems.push(`${rel(MMD_FILE)} is stale`);
  if (!fs.existsSync(PNG_FILE)) problems.push(`${rel(PNG_FILE)} is missing`);

  // The hand-written map must mention every route as `### Route: /x`
  // and every test id in backticks, so new UI never goes undocumented.
  const hand = read(HAND_MAP);
  for (const r of map.routes) {
    if (!hand.includes(`### Route: \`${r.route}\``)) problems.push(`route ${r.route} is not documented in feature-map.md`);
  }
  const allIds = new Set([...map.global.testIds, ...map.routes.flatMap((r) => r.testIds)]);
  for (const testId of allIds) {
    if (!hand.includes(`\`${testId}\``)) problems.push(`data-testid ${testId} is not documented in feature-map.md`);
  }
  return problems;
}

// Render the .mmd to .png with mermaid-cli, reusing Playwright's Chromium
// so we do not need a second browser download.
async function render() {
  const { chromium } = await import("@playwright/test");
  const config = path.join(os.tmpdir(), "feature-map-puppeteer.json");
  fs.writeFileSync(config, JSON.stringify({ executablePath: chromium.executablePath(), args: ["--no-sandbox"] }));
  const mmdc = path.join(ROOT, "node_modules/.bin/mmdc");
  execFileSync(mmdc, ["-i", MMD_FILE, "-o", PNG_FILE, "-p", config, "-b", "white", "-s", "2"], { stdio: "inherit" });
}

async function main() {
  const args = process.argv.slice(2);
  const map = buildMap();
  if (args.includes("--check")) {
    const problems = findProblems(map);
    if (problems.length) {
      console.error("Feature map is out of date:\n- " + problems.join("\n- "));
      console.error("Fix: document new routes/test ids in feature-map.md, then run npm run feature-map:render");
      process.exit(1);
    }
    console.log(`Feature map OK (${map.routes.length} routes).`);
    return;
  }
  fs.writeFileSync(JSON_FILE, JSON.stringify(map, null, 2) + "\n");
  fs.writeFileSync(MMD_FILE, toMermaid(map));
  console.log(`Wrote ${rel(JSON_FILE)} and ${rel(MMD_FILE)}`);
  if (!args.includes("--no-render")) {
    await render();
    console.log(`Rendered ${rel(PNG_FILE)}`);
  }
}

// Only run main() when called from the command line, not when a test imports us.
if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(import.meta.filename)) {
  main().catch((error) => {
    console.error(error);
    process.exit(1);
  });
}
